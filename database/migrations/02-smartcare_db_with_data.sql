-- 查看跌倒事件统计
SELECT 
    CASE status 
        WHEN 1 THEN '待处理'
        WHEN 2 THEN '已处理'
        WHEN 3 THEN '误报'
    END as status_name,
    COUNT(*) as count
FROM fall_events 
GROUP BY status;

-- 查看告警发送统计
SELECT 
    CASE send_method 
        WHEN 1 THEN '短信'
        WHEN 2 THEN 'APP推送'
        WHEN 3 THEN '电话'
    END as method_name,
    CASE send_status 
        WHEN 0 THEN '失败'
        WHEN 1 THEN '成功'
        WHEN 2 THEN '发送中'
    END as status_name,
    COUNT(*) as count
FROM alert_logs 
GROUP BY send_method, send_status;
